#!/usr/bin/env bash
# Install the ai-agents orchestration wrappers and wire them into Cursor / Claude Code.
#
#   ./install.sh [--prefix DIR] [--project DIR]... [--cursor] [--claude] [--claude-global]
#                [--agy-perms PROJECTS_DIR] [--dry-run]
#
#   --prefix DIR        where the wrappers live (default: ~/.ai-agents)
#   --project DIR       a project to wire up (repeatable); needs --cursor and/or --claude
#   --cursor            write DIR/.cursor/rules/ai-orchestration.mdc (alwaysApply)
#   --claude            add/refresh a marked block in DIR/CLAUDE.md
#   --claude-global     add/refresh the block in ~/.claude/CLAUDE.md (all Claude Code projects)
#   --agy-perms DIR     give agy (Gemini) the command allow/deny list, with file access to DIR
#                       (only if ~/.gemini/antigravity-cli/settings.json has no "permissions" yet)
#   --dry-run           print what would change, change nothing
#
# Re-running is safe: files are refreshed, user text outside the marked blocks is never touched,
# a pre-existing non-generated .mdc is backed up (*.bak) before being replaced.
set -euo pipefail
SRC="$(cd "$(dirname "$0")" && pwd)"
PREFIX="$HOME/.ai-agents"; PROJECTS=(); CURSOR=0; CLAUDE=0; CLAUDE_GLOBAL=0; AGY_DIR=""; DRY=0
while [ $# -gt 0 ]; do
  case "$1" in
    --prefix) PREFIX="$2"; shift 2;;
    --project) PROJECTS+=("$2"); shift 2;;
    --cursor) CURSOR=1; shift;;
    --claude) CLAUDE=1; shift;;
    --claude-global) CLAUDE_GLOBAL=1; shift;;
    --agy-perms) AGY_DIR="$2"; shift 2;;
    --dry-run) DRY=1; shift;;
    -h|--help) sed -n '2,19p' "$0"; exit 0;;
    *) echo "unknown option: $1" >&2; exit 2;;
  esac
done
[ ${#PROJECTS[@]} -gt 0 ] && [ $CURSOR = 0 ] && [ $CLAUDE = 0 ] && { echo "--project needs --cursor and/or --claude" >&2; exit 2; }

say() { echo "• $*"; }
run() { if [ $DRY = 1 ]; then echo "  (dry-run) $*"; else "$@"; fi; }
MARK_B='<!-- ai-agents:begin (generated by ai-agents install.sh; edit templates/RULES.md, then re-run) -->'
MARK_E='<!-- ai-agents:end -->'

mkdir -p "$PREFIX" 2>/dev/null || true
PREFIX="$(cd "$PREFIX" && pwd)"
rules() { sed "s#{{AGENTS_HOME}}#$PREFIX#g" "$SRC/templates/RULES.md"; }

# 1. wrappers
if [ "$SRC" = "$PREFIX" ]; then say "wrappers already in $PREFIX"
else
  say "copy wrappers -> $PREFIX"
  run rsync -a --exclude .git --exclude dist "$SRC/" "$PREFIX/"
fi
# Windows: files saved/extracted on the Windows side get CRLF line endings, which break bash ("$'\r': command not found")
if [ $DRY = 0 ] && grep -rlI $'\r' "$PREFIX" --include='*.sh' --include='*.py' --include='*.md' --include='*.json' --include=shadow-exclude --include=agy --include=agent >/dev/null 2>&1; then
  say "convert CRLF -> LF (Windows line endings found)"
  grep -rlI $'\r' "$PREFIX" --include='*.sh' --include='*.py' --include='*.md' --include='*.json' --include=shadow-exclude --include=agy --include=agent \
    | while IFS= read -r f; do sed -i 's/\r$//' "$f"; done
fi
run chmod +x "$PREFIX"/*.sh "$PREFIX"/testdigest.py "$PREFIX"/tests/run.sh "$PREFIX"/tests/stubs/* 2>/dev/null || true

# 2. user env file
ENVF="$HOME/.config/ai-agents/env"
if [ -f "$ENVF" ]; then say "keep existing $ENVF"
else say "create $ENVF"; run mkdir -p "$(dirname "$ENVF")"; run cp "$SRC/templates/env.example" "$ENVF"; fi

# 3. agy permissions
if [ -n "$AGY_DIR" ]; then
  AGYS="$HOME/.gemini/antigravity-cli/settings.json"; AGY_DIR="$(cd "$AGY_DIR" && pwd)"
  if [ -f "$AGYS" ] && grep -q '"permissions"' "$AGYS"; then
    say "agy settings already has permissions — not touching. Compare with $PREFIX/templates/agy-settings.example.json"
  else
    say "agy permissions -> $AGYS (file access: $AGY_DIR, /tmp)"
    if [ $DRY = 0 ]; then
      mkdir -p "$(dirname "$AGYS")"
      python3 - "$AGYS" "$SRC/templates/agy-settings.example.json" "$AGY_DIR" <<'PY'
import json, os, sys
dst, tpl, pdir = sys.argv[1:]
cur = json.load(open(dst)) if os.path.exists(dst) and os.path.getsize(dst) else {}
perm = json.loads(open(tpl).read().replace("{{PROJECTS_DIR}}", pdir))["permissions"]
cur["permissions"] = perm
json.dump(cur, open(dst, "w"), indent=2)
PY
    fi
  fi
fi

# 4. rule files
write_block() {  # $1=file : replace marked block or append it
  local f="$1" tmp; tmp="$(mktemp)"
  { echo "$MARK_B"; rules; echo "$MARK_E"; } > "$tmp"
  if [ $DRY = 1 ]; then echo "  (dry-run) refresh ai-agents block in $f"; rm -f "$tmp"; return; fi
  mkdir -p "$(dirname "$f")"; touch "$f"
  python3 - "$f" "$tmp" "$MARK_B" "$MARK_E" <<'PY'
import sys
f, blk, b, e = sys.argv[1:]
txt, new = open(f).read(), open(blk).read()
i, j = txt.find(b), txt.find(e)
if i >= 0 and j > i:
    txt = txt[:i] + new.rstrip("\n") + txt[j + len(e):]
else:
    txt = (txt.rstrip("\n") + "\n\n" if txt.strip() else "") + new
open(f, "w").write(txt)
PY
  rm -f "$tmp"
}
for P in "${PROJECTS[@]}"; do
  P="$(cd "$P" && pwd)"
  if [ $CURSOR = 1 ]; then
    F="$P/.cursor/rules/ai-orchestration.mdc"
    say "cursor rule -> $F"
    if [ $DRY = 0 ]; then
      mkdir -p "$(dirname "$F")"
      [ -f "$F" ] && ! grep -q 'generated by ai-agents install.sh' "$F" && cp "$F" "$F.bak"
      { printf -- '---\ndescription: AI orchestration — delegate implementation to Gemini/Composer sub-agents (ai-agents)\nalwaysApply: true\n---\n'
        echo "$MARK_B"; rules; echo "$MARK_E"; } > "$F"
    fi
  fi
  [ $CLAUDE = 1 ] && { say "claude block -> $P/CLAUDE.md"; write_block "$P/CLAUDE.md"; }
done
[ $CLAUDE_GLOBAL = 1 ] && { say "claude block -> ~/.claude/CLAUDE.md"; write_block "$HOME/.claude/CLAUDE.md"; }

# 5. checks
echo
if [ $DRY = 0 ]; then "$PREFIX/doctor.sh" --deps || true; fi
cat <<EOF

Next:
  1. Log in once (interactive):  agy        (Google account)   |   agent login   (Cursor account)
  2. Full check:                 $PREFIX/doctor.sh
  3. Self-test (no network):     bash $PREFIX/tests/run.sh
  4. Cursor global rule (optional): Cursor Settings → Rules → User Rules → paste the output of:
       sed "s#{{AGENTS_HOME}}#$PREFIX#g" $PREFIX/templates/RULES.md
EOF
